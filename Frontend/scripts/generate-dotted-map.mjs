/**
 * Bake dotted-map WebPs so WorldMap never inlines ~1MB SVG data URLs in HTML.
 * Uses equirectangular so pin overlays can use a simple lat/lng → viewBox map.
 */
import {
  mkdirSync,
  writeFileSync,
  unlinkSync,
  existsSync,
  statSync,
} from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import DottedMap from "dotted-map";
import sharp from "sharp";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = join(root, "public", "images", "maps");
const projectionPath = join(
  root,
  "src",
  "components",
  "ui",
  "mapProjection.ts",
);

/** Exact 2:1 — matches WorldMap SVG viewBox 800×400. */
const OUT_W = 1056;
const OUT_H = 528;

const variants = [
  { name: "dotted-world-light", color: "#34745A88" },
  { name: "dotted-world-dark", color: "#C8F13540" },
];

mkdirSync(outDir, { recursive: true });
const map = new DottedMap({
  height: 100,
  grid: "diagonal",
  projection: { name: "equirectangular" },
});

writeFileSync(
  projectionPath,
  `/**
 * Projection constants matching \`dotted-map\`
 * (height: 100, grid: diagonal, equirectangular).
 * Regenerated by scripts/generate-dotted-map.mjs — do not hand-edit casually.
 */
export const MAP_PROJECTION = {
  kind: "equirectangular" as const,
  mapWidth: ${map.width},
  mapHeight: ${map.height},
  /** proj4 eqc meters — used only if we ever need raw proj space */
  xMin: ${map.X_MIN},
  yMax: ${map.Y_MAX},
  xRange: ${map.X_RANGE},
  yRange: ${map.Y_RANGE},
  viewBoxWidth: 800,
  viewBoxHeight: 400,
} as const;
`,
);
console.log(
  `mapProjection.ts (${map.width}×${map.height} equirectangular bounds)`,
);

for (const { name, color } of variants) {
  const svg = map.getSVG({
    radius: 0.22,
    color,
    shape: "circle",
    backgroundColor: "transparent",
  });
  const webpPath = join(outDir, `${name}.webp`);
  const buf = await sharp(Buffer.from(svg), { density: 96 })
    .resize(OUT_W, OUT_H, {
      fit: "fill",
      background: { r: 0, g: 0, b: 0, alpha: 0 },
    })
    .webp({ quality: 55, alphaQuality: 60, effort: 6 })
    .toBuffer();
  writeFileSync(webpPath, buf);
  const svgPath = join(outDir, `${name}.svg`);
  if (existsSync(svgPath)) unlinkSync(svgPath);
  console.log(`${name}.webp ${statSync(webpPath).size} bytes`);
}

// Sanity: print hub pins in viewBox space via dotted-map getPin.
const hubs = [
  ["us", 38.9072, -77.0369],
  ["ca", 43.6532, -79.3832],
  ["gb", 51.5074, -0.1278],
  ["nl", 52.3676, 4.9041],
  ["de", 50.1109, 8.6821],
  ["sg", 1.3521, 103.8198],
  ["au", -33.8688, 151.2093],
  ["jp", 35.6762, 139.6503],
];
for (const [id, lat, lng] of hubs) {
  const pin = map.getPin({ lat, lng });
  const x = (pin.x / map.width) * 800;
  const y = (pin.y / map.height) * 400;
  console.log(`${id} pin→viewBox`, x.toFixed(1), y.toFixed(1));
}
